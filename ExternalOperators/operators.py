import sys
from types import SimpleNamespace
from firedrake import *

options = PETSc.Options()
Print = PETSc.Sys.Print


def interpolation_(u_, Vdst_):
    return interpolate(3*u_ + u_*u_, Vdst_)


class InterpolationExtOper(AbstractExternalOperator):
    @assemble_method(0, (0,))
    def assemble_N(self, *args, **kwargs):
        cache = self.operator_data
        cache.u.assign(self.ufl_operands[0])
        return assemble(cache.N)

    @assemble_method(1, (0, None))
    def assemble_dNdu_action(self, *args, **kwargs):
        cache = self.operator_data
        cache.u.assign(self.ufl_operands[0])
        cache.usrc_act.assign(self.argument_slots()[-1])
        return assemble(cache.dNdu_action)

    @assemble_method(1, (None, 0))
    def assemble_dNdu_adjoint_action(self, *args, **kwargs):
        cache = self.operator_data
        cache.u.assign(self.ufl_operands[0])
        cache.udst_act.assign(self.argument_slots()[0])
        return assemble(cache.dNdu_adj_action)


def build_interp_extop(usrc_, Vdst_):
        # We don't want to do any symbolic work at assembly time
        # so we will build the symbolic expressions now and stash
        # them to reuse later.
        # We build the expressions on separate variables and will
        # copy in the correct numerical values at assembly time.
        # This allows the symbolic cache to be shared across the
        # different ExternalOperator instances that might be
        # autogenerated because they can have different ufl_operands.

        # cached buffers
        u_ = Function(usrc_.function_space())
        usrc_act = Function(usrc_.function_space())
        udst_act = Function(Vdst_.dual())
        # cached expressions
        N_ = interpolation_(u_, Vdst_)
        dNdu = derivative(N_, u_)
        dNdu_action = action(dNdu, usrc_act)
        dNdu_adj_action = action(adjoint(dNdu), udst_act)

        operator_data = SimpleNamespace(
            u=u_,
            usrc_act=usrc_act,
            udst_act=udst_act,
            N=N_,
            dNdu_action=dNdu_action,
            dNdu_adj_action=dNdu_adj_action,
        )
        return InterpolationExtOper(
            usrc_,
            function_space=Vdst_,
            operator_data=operator_data,
        )

mesh = UnitIntervalMesh(options.getInt("nx", 16))
x, = SpatialCoordinate(mesh)

Vsrc = FunctionSpace(mesh, "CG", 1)
Vdst = FunctionSpace(mesh, "DG", 2)

usrc = Function(Vsrc).interpolate(cos(2*pi*x))

rsrc = Function(Vsrc).interpolate(1 + sin(4*pi*x))
rdst = Function(Vdst).interpolate(2 + sin(4*pi*x))

N = build_interp_extop(usrc, Vdst)
M = interpolation_(usrc, Vdst)

wdst = assemble(M)
udst = assemble(N)

Print(f'N: {errornorm(wdst, udst)= :.12e}')

usrc.assign(1 + usrc)

dMdu = derivative(M, usrc)
dNdu = derivative(N, usrc)

wact = assemble(action(dMdu, rsrc))
uact = assemble(action(dNdu, rsrc))

Print(f'dNdu * rsrc: {errornorm(wact, uact)= :.12e}')

usrc.assign(2 + usrc)

dMdu_adj = adjoint(dMdu)
dNdu_adj = adjoint(dNdu)

wadj = assemble(action(dMdu_adj, rdst.riesz_representation())).riesz_representation()
uadj = assemble(action(dNdu_adj, rdst.riesz_representation())).riesz_representation()

Print(f'dNdu^T * rdst action: {errornorm(wadj, uadj)= :.12e}')